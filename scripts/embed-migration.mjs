// Embeds the SQL migrations into the app so the in-app setup screen can offer
// a "Copy SQL" button. Runs automatically before `npm run build`.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const dir = `${root}supabase/migrations`;
const sql = readdirSync(dir)
  .filter((f) => f.endsWith(".sql"))
  .sort()
  .map((f) => readFileSync(`${dir}/${f}`, "utf8"))
  .join("\n");

const out = `// Generated by scripts/embed-migration.mjs from supabase/migrations. Do not edit.\nexport const SETUP_SQL = ${JSON.stringify(sql)};\n`;
writeFileSync(`${root}src/lib/generated/setup-sql.ts`, out);
console.log(`Embedded ${sql.length} characters of setup SQL`);
